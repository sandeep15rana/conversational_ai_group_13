def print_separator(char="=", length=80):
    print(char * length)

def print_section(title):
    print("\n" + "=" * 80)
    print(f" >>> {title.upper()}")
    print("=" * 80)

def run_synthetic_session(app, query: str, session_id: str, user_id: str = "sandeep_rana"):
    print_separator("-")
    print(f"[*] SESSION ID : {session_id}")
    print(f"[*] USER ID    : {user_id}")
    print(f"[*] INPUT QUERY: \"{query}\"")
    print_separator("-")
    
    config = {"configurable": {"thread_id": session_id}}
    
    initial_state = {
        "session_id": session_id,
        "user_id": user_id,
        "raw_query": query,
        "is_safe": True,
        "sanitized_query": "",
        "security_flag": None,
        "recalled_context": None,
        "user_preferences": {},
        "plan": [],
        "completed_tasks": [],
        "current_step": 0,
        "next_action": "",
        "iteration_count": 0,
        "max_iterations": 8,
        "research_data": [],
        "calculated_metrics": {},
        "draft_response": "",
        "final_output": "",
        "is_hallucination_detected": False,
        "errors": [],
        "execution_trace": []
    }
    
    start_time = time.time()
    result = app.invoke(initial_state, config=config)
    elapsed = time.time() - start_time
    
    # 1. Print Execution Trace Log
    print("\n[+] STEP-BY-STEP ORCHESTRATION TRACE:")
    for idx, trace_line in enumerate(result.get("execution_trace", []), start=1):
        print(f"    {idx:02d}. {trace_line}")
        
    # 2. Print Plan DAG generated by Supervisor
    print("\n[+] SUPERVISOR DAG EXECUTION PLAN:")
    for task_idx, task in enumerate(result.get("plan", []), start=1):
        status = "COMPLETED" if task in result.get("completed_tasks", []) else "PENDING"
        print(f"    [{status}] Task {task_idx}: {task}")
        
    # 3. Print Calculated Metrics & Research Status
    if result.get("calculated_metrics"):
        print("\n[+] ANALYTICAL ENGINE COMPUTATIONS:")
        for k, v in result["calculated_metrics"].items():
            print(f"    - {k}: {v}")
            
    # 4. Print Final Delivered Output
    print("\n[+] FINAL DELIVERED RESPONSE:")
    print_separator("-")
    print(result.get("final_output", "No output generated."))
    print_separator("-")
    print(f"[i] Execution Time: {elapsed:.3f}s | Iterations: {result.get('iteration_count', 0)}/8 | Safe: {result.get('is_safe')}\n")
    
    return result

